// Helper: all lessons flat list
export const ALL_LESSONS: Lesson[] = LESSON_BLOCKS.flatMap((b) => b.lessons)

// Helper: get lesson by id
export function getLessonById(id: string): Lesson | undefined {
  return ALL_LESSONS.find((l) => l.id === id)
}

// Helper: get next lesson
export function getNextLesson(currentId: string): Lesson | undefined {
  const idx = ALL_LESSONS.findIndex((l) => l.id === currentId)
  return idx >= 0 ? ALL_LESSONS[idx + 1] : undefined
}
